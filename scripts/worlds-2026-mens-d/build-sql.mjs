// Writes supabase/precheck-2026-worlds-mens-d.sql (read-only),
// supabase/load-2026-worlds-mens-d.sql and
// supabase/rollback-2026-worlds-mens-d.sql from sheet.mjs.
//   node scripts/worlds-2026-mens-d/build-sql.mjs          # write files
//   node scripts/worlds-2026-mens-d/build-sql.mjs --check  # fail if stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import {
  TOURNAMENT_ID, DIVISION_NAME, DAYS, VENUES, TEAMS, GAMES, TIME_ZONE, OLD_MENS, fieldText, parseToken,
} from "./sheet.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const LOAD = path.join(root, "supabase/load-2026-worlds-mens-d.sql");
const ROLLBACK = path.join(root, "supabase/rollback-2026-worlds-mens-d.sql");
const PRECHECK = path.join(root, "supabase/precheck-2026-worlds-mens-d.sql");

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);

function gameValues(game) {
  const a = parseToken(game.a);
  const b = parseToken(game.b);
  const name = (t) => (t.kind === "team" ? q(t.name) : "null");
  const srcN = (t) => (t.kind === "team" ? "null" : String(t.n));
  const srcR = (t) => (t.kind === "W" ? "'winner'" : t.kind === "L" ? "'loser'" : "null");
  return `    (${game.n}, ${q(game.side)}, ${name(a)}, ${name(b)}, ${srcN(a)}, ${srcR(a)}, ${srcN(b)}, ${srcR(b)}, ${q(`${DAYS[game.day]} ${game.at}`)}, ${q(fieldText(game))})`;
}

export function buildLoadSql() {
  const venuesJson = JSON.stringify(VENUES.map(({ name, address, field_prefix, map_url }) => ({ name, address, field_prefix, map_url })));
  return `-- AFA World Series 2026 — Men's D: division, 16 teams, venues, 35-game 3GG bracket.
-- GENERATED by scripts/worlds-2026-mens-d/build-sql.mjs from sheet.mjs. Do not hand-edit.
--
-- Run order (SQL editor, live project, only with J.D.'s OK):
--   0. supabase/precheck-2026-worlds-mens-d.sql   read-only counts
--   1. supabase/migration-2026-11-08-tournament-venues.sql    adds tournaments.venues
--   2. supabase/migration-2026-11-08-tournament-timezone.sql  adds tournaments.timezone
--   3. this file (one statement block; it is its own transaction)
-- NOT RUN.
--
-- What it writes (tournament 2026-afa-world-series, ${TOURNAMENT_ID}):
--   tournaments  1 row updated  venues = Hunter Park + Pioneer Park (name, address, map link),
--                                timezone = '${TIME_ZONE}'
--   divisions    1 row deleted  the classless "Men's" placeholder (${OLD_MENS.id}) —
--                               only if nothing at all points at it (see step 0)
--   divisions    1 row inserted "${DIVISION_NAME}" (mens, class D)
--   registrations ${TEAMS.length} rows inserted, confirmed, no manager / roster (team-without-manager.sql)
--   brackets     1 row inserted (main, three_gg_hybrid, 16 teams)
--   games        ${GAMES.length} rows inserted (round = sheet G#, slot 0), then Winner/Loser links
--
-- Idempotent: re-running changes nothing that already matches. It refuses
-- (raises, rolls back) if Men's D already has a scored game or games that
-- are not this sheet's G1–G35, or if the old "Men's" division has anything
-- attached (registrations, games, brackets, pool games, placements, child
-- divisions, or a row in any other table with a foreign key to it).
--
-- Times: the sheet's clock times are Mesquite wall clock, stored as true
-- Pacific instants (v_tz). The site shows them in tournaments.timezone with
-- the zone's name ("2 PM PST"); the calendar export carries UTC instants.

do $$
declare
  v_tz text := ${q(TIME_ZONE)};
  v_old uuid;
  v_regs int; v_mgr int; v_roster int; v_games int; v_brackets int; v_pool int; v_place int; v_kids int; v_fk int;
  v_fkrec record;
  v_tournament uuid := '${TOURNAMENT_ID}';
  v_class uuid;
  v_div uuid;
  v_teams text[] := array[${TEAMS.map(q).join(", ")}];
  v_bad int;
  v_n int;
begin
  if not exists (select 1 from public.tournaments where id = v_tournament and slug = '2026-afa-world-series') then
    raise exception 'AFA World Series tournament % not found', v_tournament;
  end if;

  select id into v_class from public.classes where name = 'D';
  if v_class is null then raise exception 'class D not found'; end if;

  -- 1. Venues (two parks, map links) and the tournament's time zone
  update public.tournaments
     set venues = ${q(venuesJson)}::jsonb,
         timezone = v_tz
   where id = v_tournament
     and (venues is distinct from ${q(venuesJson)}::jsonb or timezone is distinct from v_tz);

  -- 1b. Remove the classless "Men's" placeholder — only if it is empty.
  -- Matched by tournament, exact name and NULL class, so nothing else can
  -- be hit; its id must be the one the rollback recreates.
  select id into v_old from public.divisions
   where tournament_id = v_tournament and name = ${q(OLD_MENS.name)} and class_id is null;
  if v_old is not null then
    if v_old <> ${q(OLD_MENS.id)}::uuid then
      raise exception 'old Men''s division has id %, expected ${OLD_MENS.id}; not touching it', v_old;
    end if;
    select count(*) into v_regs from public.registrations where division_id = v_old;
    select count(*) into v_mgr from public.registrations
     where division_id = v_old and coalesce(btrim(manager_name), '') <> '';
    select count(*) into v_roster from public.roster_members m
      join public.registrations r on r.id = m.registration_id where r.division_id = v_old;
    select count(*) into v_games from public.games where division_id = v_old;
    select count(*) into v_brackets from public.brackets where division_id = v_old;
    select count(*) into v_pool from public.pool_games where division_id = v_old;
    select count(*) into v_place from public.placements where division_id = v_old;
    select count(*) into v_kids from public.divisions where parent_division_id = v_old;
    -- Anything else with a foreign key to divisions (tables this repo does not know about).
    v_fk := 0;
    for v_fkrec in
      select cl.relname as tbl, att.attname as col
        from pg_constraint con
        join pg_class cl on cl.oid = con.conrelid
        join pg_namespace ns on ns.oid = cl.relnamespace
        join pg_attribute att on att.attrelid = con.conrelid and att.attnum = con.conkey[1]
       where con.contype = 'f' and con.confrelid = 'public.divisions'::regclass
         and ns.nspname = 'public' and array_length(con.conkey, 1) = 1
    loop
      execute format('select count(*) from public.%I where %I = $1', v_fkrec.tbl, v_fkrec.col)
        into v_n using v_old;
      v_fk := v_fk + v_n;
    end loop;
    if v_regs + v_mgr + v_roster + v_games + v_brackets + v_pool + v_place + v_kids + v_fk > 0 then
      raise exception 'old Men''s division is not empty — registrations %, with manager %, roster members %, games %, brackets %, pool games %, placements %, child divisions %, rows referencing it %; nothing changed',
        v_regs, v_mgr, v_roster, v_games, v_brackets, v_pool, v_place, v_kids, v_fk;
    end if;
    delete from public.divisions
     where id = v_old and tournament_id = v_tournament and name = ${q(OLD_MENS.name)} and class_id is null;
    raise notice 'old Men''s division deleted (it was empty)';
  end if;

  -- 2. Division
  insert into public.divisions (
    tournament_id, name, display_name, gender, class_id, bracket_type,
    sort_order, day_date, day_label, min_teams, min_men, min_women
  )
  values (
    v_tournament, ${q(DIVISION_NAME)}, ${q(DIVISION_NAME)}, 'mens', v_class, 'double_elimination',
    0, date '${DAYS.THU}', 'Thu–Fri, Nov 12–13', 6, 10, 0
  )
  on conflict (tournament_id, name) do nothing;

  select id into v_div from public.divisions where tournament_id = v_tournament and name = ${q(DIVISION_NAME)};

  -- Refuse to touch a bracket someone has started scoring, or a different one.
  select count(*) into v_bad from public.games
   where division_id = v_div
     and (status = 'final' or bracket_group <> 'main' or slot <> 0 or round not between 1 and ${GAMES.length});
  if v_bad > 0 then
    raise exception 'Men''s D already has % scored or foreign game rows; not loading', v_bad;
  end if;

  -- 3. Teams: one live registration each, no manager, no roster.
  insert into public.registrations (
    tournament_id, division_id, team_name, class_id, manager_name, manager_email, status
  )
  select v_tournament, v_div, t, v_class, null, null, 'confirmed'
    from unnest(v_teams) as t
   where not exists (
     select 1 from public.registrations r
      where r.division_id = v_div and r.status <> 'withdrawn'
        and lower(btrim(r.team_name)) = lower(btrim(t))
   );
  get diagnostics v_n = row_count;
  raise notice 'registrations inserted: %', v_n;

  -- 4. Bracket metadata
  insert into public.brackets (division_id, bracket_group, format, team_count, bracket_size)
  values (v_div, 'main', 'three_gg_hybrid', ${TEAMS.length}, 16)
  on conflict (division_id, bracket_group) do update
    set format = excluded.format, team_count = excluded.team_count, bracket_size = excluded.bracket_size;

  -- 5. Games. round = the sheet's game number (paper G#), slot 0.
  create temp table _sheet (
    n int primary key, side text, t1 text, t2 text,
    s1 int, r1 text, s2 int, r2 text, at_local text, field text
  ) on commit drop;
  insert into _sheet values
${GAMES.map(gameValues).join(",\n")};

  -- A row whose side changed would collide on the unique key differently;
  -- clear pending rows of this division that sit on the wrong side.
  delete from public.games g using _sheet s
   where g.division_id = v_div and g.bracket_group = 'main' and g.round = s.n
     and g.bracket_side <> s.side and g.status = 'pending';

  insert into public.games (
    division_id, bracket_group, bracket_side, round, slot,
    team1_name, team2_name, field, scheduled_time, status
  )
  select v_div, 'main', s.side, s.n, 0, s.t1, s.t2, s.field,
         (s.at_local::timestamp at time zone v_tz), 'pending'
    from _sheet s
  on conflict (division_id, bracket_group, bracket_side, round, slot) do update
    set team1_name = excluded.team1_name,
        team2_name = excluded.team2_name,
        field = excluded.field,
        scheduled_time = excluded.scheduled_time,
        updated_at = now()
    where public.games.status = 'pending'
      and (public.games.team1_name, public.games.team2_name, public.games.field, public.games.scheduled_time)
          is distinct from (excluded.team1_name, excluded.team2_name, excluded.field, excluded.scheduled_time);

  -- 6. Winner/Loser links by sheet G#.
  update public.games g
     set team1_source_game_id = f1.id,
         team1_source_result = s.r1,
         team2_source_game_id = f2.id,
         team2_source_result = s.r2,
         updated_at = now()
    from _sheet s
    left join public.games f1 on f1.division_id = v_div and f1.bracket_group = 'main' and f1.round = s.s1
    left join public.games f2 on f2.division_id = v_div and f2.bracket_group = 'main' and f2.round = s.s2
   where g.division_id = v_div and g.bracket_group = 'main' and g.round = s.n
     and (g.team1_source_game_id, g.team1_source_result, g.team2_source_game_id, g.team2_source_result)
         is distinct from (f1.id, s.r1, f2.id, s.r2);

  select count(*) into v_n from public.games where division_id = v_div;
  if v_n <> ${GAMES.length} then raise exception 'expected ${GAMES.length} Men''s D games, found %', v_n; end if;
  select count(*) into v_n from public.games
   where division_id = v_div
     and ((team1_name is null and team1_source_game_id is null) or (team2_name is null and team2_source_game_id is null));
  if v_n <> 0 then raise exception '% Men''s D games have an unfed slot', v_n; end if;
  raise notice 'Men''s D loaded: division %, ${GAMES.length} games', v_div;
end $$;

-- Check (read-only):
-- select round as g, bracket_side, team1_name, team2_name, field,
--        to_char(scheduled_time at time zone '${TIME_ZONE}', 'Dy HH12:MI AM') as mesquite_time
--   from games where division_id = (select id from divisions
--     where tournament_id = '${TOURNAMENT_ID}' and name = ${q(DIVISION_NAME)})
--  order by round;
`;
}

export function buildRollbackSql() {
  return `-- Undo supabase/load-2026-worlds-mens-d.sql.
-- GENERATED by scripts/worlds-2026-mens-d/build-sql.mjs. Do not hand-edit.
--
-- Deletes the Men's D division of 2026-afa-world-series with its games and
-- bracket (cascade) and its registrations, clears tournaments.venues and
-- tournaments.timezone, and recreates the old classless "Men's" division with
-- the exact column values it had (id ${OLD_MENS.id}, captured from the public
-- site 2026-11-08; any column the public read did not show takes its default).
-- Refuses if any Men's D game has a score, or any Men's D registration has a
-- manager or roster members — at that point it is real data, not the load.
-- Does NOT drop the tournaments.venues / timezone columns (see their migrations).

do $$
declare
  v_tournament uuid := '${TOURNAMENT_ID}';
  v_div uuid;
  v_n int;
begin
  select id into v_div from public.divisions where tournament_id = v_tournament and name = ${q(DIVISION_NAME)};
  if v_div is null then raise notice 'Men''s D not present; nothing to undo'; end if;

  if v_div is not null then
    select count(*) into v_n from public.games where division_id = v_div and status = 'final';
    if v_n > 0 then raise exception 'Men''s D has % scored games; not rolling back', v_n; end if;

    select count(*) into v_n from public.registrations r
     where r.division_id = v_div
       and (r.manager_name is not null
            or exists (select 1 from public.roster_members m where m.registration_id = r.id));
    if v_n > 0 then raise exception 'Men''s D has % registrations with a manager or roster; not rolling back', v_n; end if;

    update public.games set team1_source_game_id = null, team2_source_game_id = null where division_id = v_div;
    delete from public.games where division_id = v_div;
    delete from public.brackets where division_id = v_div;
    delete from public.registrations where division_id = v_div;
    delete from public.divisions where id = v_div;
  end if;

  update public.tournaments set venues = null, timezone = null
   where id = v_tournament and (venues is not null or timezone is not null);

  insert into public.divisions (
    id, tournament_id, name, display_name, gender, class_id, bracket_type, sort_order,
    day_date, day_label, min_teams, max_teams, min_men, min_women, seed_order,
    third_life_teams, parent_division_id, source_url, bracket_confirmed_at,
    bracket_confirmed_by, created_at
  ) values (
    ${q(OLD_MENS.id)}, v_tournament, ${q(OLD_MENS.name)}, ${q(OLD_MENS.display_name)}, ${q(OLD_MENS.gender)}, null,
    ${q(OLD_MENS.bracket_type)}, ${OLD_MENS.sort_order}, date ${q(OLD_MENS.day_date)}, ${q(OLD_MENS.day_label)},
    ${OLD_MENS.min_teams}, null, ${OLD_MENS.min_men}, ${OLD_MENS.min_women}, null,
    '{}', null, null, null,
    null, timestamptz ${q(OLD_MENS.created_at)}
  )
  on conflict do nothing;
  raise notice 'Men''s D rolled back; old Men''s division present';
end $$;
`;
}

export function buildPrecheckSql() {
  const div = `(select id from public.divisions where tournament_id = '${TOURNAMENT_ID}' and name = ${q(OLD_MENS.name)} and class_id is null)`;
  return `-- READ-ONLY pre-check for supabase/load-2026-worlds-mens-d.sql. SELECTs only.
-- GENERATED by scripts/worlds-2026-mens-d/build-sql.mjs. Do not hand-edit.
-- Run it first. The load deletes the old classless "Men's" division only if
-- every count in the first result is 0 (it also checks any other table that
-- has a foreign key to divisions, which this file cannot list generically).

select
  (select count(*) from public.divisions where tournament_id = '${TOURNAMENT_ID}' and name = ${q(OLD_MENS.name)} and class_id is null) as old_mens_division,
  (select count(*) from public.divisions where id = ${q(OLD_MENS.id)}) as old_mens_expected_id,
  (select count(*) from public.registrations where division_id = ${div}) as registrations,
  (select count(*) from public.registrations where division_id = ${div} and status <> 'withdrawn') as live_registrations,
  (select count(*) from public.registrations where division_id = ${div} and coalesce(btrim(manager_name), '') <> '') as with_manager,
  (select count(*) from public.roster_members m join public.registrations r on r.id = m.registration_id where r.division_id = ${div}) as roster_members,
  (select count(*) from public.games where division_id = ${div}) as games,
  (select count(*) from public.brackets where division_id = ${div}) as brackets,
  (select count(*) from public.pool_games where division_id = ${div}) as pool_games,
  (select count(*) from public.placements where division_id = ${div}) as placements,
  (select count(*) from public.divisions where parent_division_id = ${div}) as child_divisions;

-- Men's D not loaded yet (all 0 on a first run), and the new columns.
select
  (select count(*) from public.divisions where tournament_id = '${TOURNAMENT_ID}' and name = ${q(DIVISION_NAME)}) as mens_d_division,
  (select count(*) from public.registrations r join public.divisions d on d.id = r.division_id
    where d.tournament_id = '${TOURNAMENT_ID}' and d.name = ${q(DIVISION_NAME)}) as mens_d_registrations,
  (select count(*) from public.games g join public.divisions d on d.id = g.division_id
    where d.tournament_id = '${TOURNAMENT_ID}' and d.name = ${q(DIVISION_NAME)}) as mens_d_games,
  (select count(*) from information_schema.columns where table_schema = 'public' and table_name = 'tournaments' and column_name = 'venues') as has_venues_column,
  (select count(*) from information_schema.columns where table_schema = 'public' and table_name = 'tournaments' and column_name = 'timezone') as has_timezone_column;

-- Other tables with a foreign key to divisions (the load counts these too).
select cl.relname as table_name
  from pg_constraint con
  join pg_class cl on cl.oid = con.conrelid
 where con.contype = 'f' and con.confrelid = 'public.divisions'::regclass
 order by 1;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const load = buildLoadSql();
  const rollback = buildRollbackSql();
  const precheck = buildPrecheckSql();
  if (process.argv.includes("--check")) {
    const stale = [[LOAD, load], [ROLLBACK, rollback], [PRECHECK, precheck]].filter(([f, s]) => {
      try { return readFileSync(f, "utf8") !== s; } catch { return true; }
    });
    if (stale.length) {
      console.error("stale:", stale.map(([f]) => path.relative(root, f)).join(", "));
      process.exit(1);
    }
  } else {
    writeFileSync(LOAD, load);
    writeFileSync(ROLLBACK, rollback);
    writeFileSync(PRECHECK, precheck);
    console.log("wrote", [LOAD, ROLLBACK, PRECHECK].map((f) => path.relative(root, f)).join(" "));
  }
}
