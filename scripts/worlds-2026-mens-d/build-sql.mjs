// Writes supabase/load-2026-worlds-mens-d.sql and
// supabase/rollback-2026-worlds-mens-d.sql from sheet.mjs.
//   node scripts/worlds-2026-mens-d/build-sql.mjs          # write files
//   node scripts/worlds-2026-mens-d/build-sql.mjs --check  # fail if stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import {
  TOURNAMENT_ID, DIVISION_NAME, DAYS, VENUES, TEAMS, GAMES, fieldText, parseToken,
} from "./sheet.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const LOAD = path.join(root, "supabase/load-2026-worlds-mens-d.sql");
const ROLLBACK = path.join(root, "supabase/rollback-2026-worlds-mens-d.sql");

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);

function gameValues(game) {
  const a = parseToken(game.a);
  const b = parseToken(game.b);
  const name = (t) => (t.kind === "team" ? q(t.name) : "null");
  const srcN = (t) => (t.kind === "team" ? "null" : String(t.n));
  const srcR = (t) => (t.kind === "W" ? "'winner'" : t.kind === "L" ? "'loser'" : "null");
  return `    (${game.n}, ${q(game.side)}, ${name(a)}, ${name(b)}, ${srcN(a)}, ${srcR(a)}, ${srcN(b)}, ${srcR(b)}, ${q(`${DAYS[game.day]} ${game.at}`)}, ${q(fieldText(game))})`;
}

export function buildLoadSql() {
  const venuesJson = JSON.stringify(VENUES.map(({ name, address, field_prefix, map_url }) => ({ name, address, field_prefix, map_url })));
  return `-- AFA World Series 2026 — Men's D: division, 16 teams, venues, 35-game 3GG bracket.
-- GENERATED by scripts/worlds-2026-mens-d/build-sql.mjs from sheet.mjs. Do not hand-edit.
--
-- Needs supabase/migration-2026-11-08-tournament-venues.sql first (adds tournaments.venues).
-- NOT RUN. Run only with J.D.'s OK, against the live project, in the SQL editor
-- (one statement block; it is its own transaction).
--
-- What it writes (tournament 2026-afa-world-series, ${TOURNAMENT_ID}):
--   tournaments  1 row updated  venues = Hunter Park + Pioneer Park (name, address, map link)
--   divisions    1 row inserted "${DIVISION_NAME}" (mens, class D)
--   registrations ${TEAMS.length} rows inserted, confirmed, no manager / roster (team-without-manager.sql)
--   brackets     1 row inserted (main, three_gg_hybrid, 16 teams)
--   games        ${GAMES.length} rows inserted (round = sheet G#, slot 0), then Winner/Loser links
--
-- Idempotent: re-running changes nothing that already matches. It refuses
-- (raises, rolls back) if Men's D already has a scored game or games that
-- are not this sheet's G1–G35.
--
-- Times. The sheet's times are Mesquite wall clock (Pacific). The site
-- renders every game in America/Denver (lib/bracket/tree.js LEAGUE_TZ).
-- v_tz below is the zone the sheet's wall-clock times are stored in:
--   'America/Denver'       site shows the sheet's times (2 PM reads 2 PM);
--                          the .ics calendar export is 1 hour early in Mesquite.
--   'America/Los_Angeles'  true instants; the site would show 3 PM for a 2 PM game.
-- Default is 'America/Denver' so every screen matches the paper.

do $$
declare
  v_tz text := 'America/Denver';
  v_tournament uuid := '${TOURNAMENT_ID}';
  v_class uuid;
  v_div uuid;
  v_teams text[] := array[${TEAMS.map(q).join(", ")}];
  v_bad int;
  v_n int;
begin
  if not exists (select 1 from public.tournaments where id = v_tournament and slug = '2026-afa-world-series') then
    raise exception 'AFA World Series tournament % not found', v_tournament;
  end if;

  select id into v_class from public.classes where name = 'D';
  if v_class is null then raise exception 'class D not found'; end if;

  -- 1. Venues (two parks, map links)
  update public.tournaments
     set venues = ${q(venuesJson)}::jsonb
   where id = v_tournament
     and venues is distinct from ${q(venuesJson)}::jsonb;

  -- 2. Division
  insert into public.divisions (
    tournament_id, name, display_name, gender, class_id, bracket_type,
    sort_order, day_date, day_label, min_teams, min_men, min_women
  )
  values (
    v_tournament, ${q(DIVISION_NAME)}, ${q(DIVISION_NAME)}, 'mens', v_class, 'double_elimination',
    0, date '${DAYS.THU}', 'Thu–Fri, Nov 12–13', 6, 10, 0
  )
  on conflict (tournament_id, name) do nothing;

  select id into v_div from public.divisions where tournament_id = v_tournament and name = ${q(DIVISION_NAME)};

  -- Refuse to touch a bracket someone has started scoring, or a different one.
  select count(*) into v_bad from public.games
   where division_id = v_div
     and (status = 'final' or bracket_group <> 'main' or slot <> 0 or round not between 1 and ${GAMES.length});
  if v_bad > 0 then
    raise exception 'Men''s D already has % scored or foreign game rows; not loading', v_bad;
  end if;

  -- 3. Teams: one live registration each, no manager, no roster.
  insert into public.registrations (
    tournament_id, division_id, team_name, class_id, manager_name, manager_email, status
  )
  select v_tournament, v_div, t, v_class, null, null, 'confirmed'
    from unnest(v_teams) as t
   where not exists (
     select 1 from public.registrations r
      where r.division_id = v_div and r.status <> 'withdrawn'
        and lower(btrim(r.team_name)) = lower(btrim(t))
   );
  get diagnostics v_n = row_count;
  raise notice 'registrations inserted: %', v_n;

  -- 4. Bracket metadata
  insert into public.brackets (division_id, bracket_group, format, team_count, bracket_size)
  values (v_div, 'main', 'three_gg_hybrid', ${TEAMS.length}, 16)
  on conflict (division_id, bracket_group) do update
    set format = excluded.format, team_count = excluded.team_count, bracket_size = excluded.bracket_size;

  -- 5. Games. round = the sheet's game number (paper G#), slot 0.
  create temp table _sheet (
    n int primary key, side text, t1 text, t2 text,
    s1 int, r1 text, s2 int, r2 text, at_local text, field text
  ) on commit drop;
  insert into _sheet values
${GAMES.map(gameValues).join(",\n")};

  -- A row whose side changed would collide on the unique key differently;
  -- clear pending rows of this division that sit on the wrong side.
  delete from public.games g using _sheet s
   where g.division_id = v_div and g.bracket_group = 'main' and g.round = s.n
     and g.bracket_side <> s.side and g.status = 'pending';

  insert into public.games (
    division_id, bracket_group, bracket_side, round, slot,
    team1_name, team2_name, field, scheduled_time, status
  )
  select v_div, 'main', s.side, s.n, 0, s.t1, s.t2, s.field,
         (s.at_local::timestamp at time zone v_tz), 'pending'
    from _sheet s
  on conflict (division_id, bracket_group, bracket_side, round, slot) do update
    set team1_name = excluded.team1_name,
        team2_name = excluded.team2_name,
        field = excluded.field,
        scheduled_time = excluded.scheduled_time,
        updated_at = now()
    where public.games.status = 'pending'
      and (public.games.team1_name, public.games.team2_name, public.games.field, public.games.scheduled_time)
          is distinct from (excluded.team1_name, excluded.team2_name, excluded.field, excluded.scheduled_time);

  -- 6. Winner/Loser links by sheet G#.
  update public.games g
     set team1_source_game_id = f1.id,
         team1_source_result = s.r1,
         team2_source_game_id = f2.id,
         team2_source_result = s.r2,
         updated_at = now()
    from _sheet s
    left join public.games f1 on f1.division_id = v_div and f1.bracket_group = 'main' and f1.round = s.s1
    left join public.games f2 on f2.division_id = v_div and f2.bracket_group = 'main' and f2.round = s.s2
   where g.division_id = v_div and g.bracket_group = 'main' and g.round = s.n
     and (g.team1_source_game_id, g.team1_source_result, g.team2_source_game_id, g.team2_source_result)
         is distinct from (f1.id, s.r1, f2.id, s.r2);

  select count(*) into v_n from public.games where division_id = v_div;
  if v_n <> ${GAMES.length} then raise exception 'expected ${GAMES.length} Men''s D games, found %', v_n; end if;
  select count(*) into v_n from public.games
   where division_id = v_div
     and ((team1_name is null and team1_source_game_id is null) or (team2_name is null and team2_source_game_id is null));
  if v_n <> 0 then raise exception '% Men''s D games have an unfed slot', v_n; end if;
  raise notice 'Men''s D loaded: division %, ${GAMES.length} games', v_div;
end $$;

-- Check (read-only):
-- select round as g, bracket_side, team1_name, team2_name, field,
--        to_char(scheduled_time at time zone 'America/Denver', 'Dy HH12:MI AM') as shown_on_site
--   from games where division_id = (select id from divisions
--     where tournament_id = '${TOURNAMENT_ID}' and name = ${q(DIVISION_NAME)})
--  order by round;
`;
}

export function buildRollbackSql() {
  return `-- Undo supabase/load-2026-worlds-mens-d.sql.
-- GENERATED by scripts/worlds-2026-mens-d/build-sql.mjs. Do not hand-edit.
--
-- Deletes the Men's D division of 2026-afa-world-series with its games and
-- bracket (cascade) and its registrations, and clears tournaments.venues.
-- Refuses if any Men's D game has a score, or any Men's D registration has a
-- manager or roster members — at that point it is real data, not the load.
-- Does NOT drop the tournaments.venues column (see the venues migration).

do $$
declare
  v_tournament uuid := '${TOURNAMENT_ID}';
  v_div uuid;
  v_n int;
begin
  select id into v_div from public.divisions where tournament_id = v_tournament and name = ${q(DIVISION_NAME)};
  if v_div is null then raise notice 'Men''s D not present; nothing to undo'; end if;

  if v_div is not null then
    select count(*) into v_n from public.games where division_id = v_div and status = 'final';
    if v_n > 0 then raise exception 'Men''s D has % scored games; not rolling back', v_n; end if;

    select count(*) into v_n from public.registrations r
     where r.division_id = v_div
       and (r.manager_name is not null
            or exists (select 1 from public.roster_members m where m.registration_id = r.id));
    if v_n > 0 then raise exception 'Men''s D has % registrations with a manager or roster; not rolling back', v_n; end if;

    update public.games set team1_source_game_id = null, team2_source_game_id = null where division_id = v_div;
    delete from public.games where division_id = v_div;
    delete from public.brackets where division_id = v_div;
    delete from public.registrations where division_id = v_div;
    delete from public.divisions where id = v_div;
  end if;

  update public.tournaments set venues = null where id = v_tournament and venues is not null;
  raise notice 'Men''s D rolled back';
end $$;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const load = buildLoadSql();
  const rollback = buildRollbackSql();
  if (process.argv.includes("--check")) {
    const stale = [[LOAD, load], [ROLLBACK, rollback]].filter(([f, s]) => {
      try { return readFileSync(f, "utf8") !== s; } catch { return true; }
    });
    if (stale.length) {
      console.error("stale:", stale.map(([f]) => path.relative(root, f)).join(", "));
      process.exit(1);
    }
  } else {
    writeFileSync(LOAD, load);
    writeFileSync(ROLLBACK, rollback);
    console.log("wrote", path.relative(root, LOAD), path.relative(root, ROLLBACK));
  }
}
